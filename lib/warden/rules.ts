// Attack-pattern rules. Each rule names the attack type it evidences, a base confidence,
// and a plain-words reason. `on: "norm"` rules run on normalised, lower-cased text (look-alike
// letters, leetspeak and spaced letters already undone); `on: "raw"` rules run on the original.
//
// Base confidence is deliberately modest for patterns that also appear in normal business
// text; context (who it is addressed to, whether it is hidden, concealment, targets) lifts it.

import type { AttackType } from "./types";

export interface Rule {
  id: string;
  type: AttackType;
  on: "norm" | "raw";
  re: RegExp;
  base: number;
  why: string;
  /** Suppress when a negation sits just before the match (or inside it, for SOV languages). */
  negatable?: boolean;
  /** This pattern is ambiguous on its own: needs an AI addressee, hidden text or concealment to count. */
  needsContext?: boolean;
  /** Extra check on the matched text / sentence. */
  check?: (m: RegExpMatchArray, sentence: string) => boolean;
}

